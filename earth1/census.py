def regional_force_norms(region: str):
    """Average Hofstede dims across countries in a region that have data."""
    codes = countries_in_region(region)
    has_data = [FORCE_NORMS[c] for c in codes if c in FORCE_NORMS]
    if not has_data:
        return {"pdi": 50, "idv": 50, "mas": 50, "uai": 50, "lto": 50, "ind": 50}
    keys = ["pdi", "idv", "mas", "uai", "lto", "ind"]
    return {k: round(sum(n[k] for n in has_data) / len(has_data), 1) for k in keys}


def effective_force_norms(iso2: str):
    """Hofstede norms: published if available, regional average otherwise."""
    direct = FORCE_NORMS.get(iso2)
    if direct:
        return {k: float(v) for k, v in direct.items()}
    region = get_region(iso2)
    if region:
        return regional_force_norms(region)
    return {"pdi": 50.0, "idv": 50.0, "mas": 50.0, "uai": 50.0, "lto": 50.0, "ind": 50.0}
